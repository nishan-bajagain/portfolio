export const skillIconOptions = Object.keys(icons).map((value) => ({
  value,
  label: value.replace(/^ri-/, "").replace(/-(line|fill)$/, "").replace(/-/g, " "),
}))

export function LegacyIcon({ className = "" }: { className?: string }) {
  const legacyName = className.split(/\s+/).find((name) => name.startsWith("ri-")) || ""
  const Icon = icons[legacyName] || Code2
  const styles = className.split(/\s+/).filter((name) => !name.startsWith("ri-")).join(" ")
  return (
    <Icon
      aria-hidden="true"
      className={`inline-block align-[-0.125em] ${styles}`}
      style={{ width: "1em", height: "1em" }}
      strokeWidth={2}
    />
  )
}
